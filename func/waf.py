_BODY_SCAN_LIMIT = 200_000  # bytes of body inspected per response


def _header_lookup(headers, name: str) -> str:
    try:
        value = headers.get(name)
    except Exception:
        value = None
    return (value or "").lower()


def detect_waf(response) -> str | None:
    """Best effort WAF identification from headers/cookies/body."""
    if response is None:
        return None
    headers = getattr(response, "headers", {}) or {}
    header_names = {key.lower() for key in headers.keys()}
    server = _header_lookup(headers, "server")
    cookie_header = _header_lookup(headers, "set-cookie")
    try:
        body = (response.text or "")[:_BODY_SCAN_LIMIT].lower()
    except Exception:
        body = ""
        try:
            body = response.content[:_BODY_SCAN_LIMIT].decode("utf-8", "replace").lower()
        except Exception:
            body = ""

    for name, signature in WAF_SIGNATURES.items():
        for header in signature["headers"]:
            if header in header_names or _header_lookup(headers, header):
                return name
        for server_token in signature["server"]:
            if server_token in server:
                return name
        for cookie in signature["cookies"]:
            if cookie and cookie in cookie_header:
                return name
        for pattern in signature["body"]:
            if re.search(pattern, body):
                # generic checks require a hard block status or a 4xx page
                if name == "generic-waf" and getattr(response, "status_code", 200) < 400:
                    continue
                return name
    return None


def is_blocked(response) -> bool:
    if response is None:
        return False
    status = getattr(response, "status_code", 200)
    if status in BLOCK_CODES:
        return True
    if status == 200:
        # interstitials are frequently served with HTTP 200 - only very
        # specific markers are accepted here so sites that simply embed a
        # CAPTCHA in their login form are not flagged.
        body = ""
        try:
            body = (response.text or "")[:20_000].lower()
        except Exception:
            return False
        strong_markers = (
            "just a moment",
            "cf-chl",
            "checking your browser before",
            "enable javascript and cookies to continue",
            "ddos-guard",
            "_incapsula_",
            "incapsula incident id",
            "wordfence has blocked",
            "request has been blocked",
        )
        if any(marker in body for marker in strong_markers):
            return True
    return False


def looks_like_login_page(response) -> bool:
    if response is None or getattr(response, "status_code", 0) >= 400:
        return False
    try:
        body = (response.text or "")[:200_000].lower()
    except Exception:
        return False
    markers = ("user_login", 'name="log"', "wp-login.php", "loginform", "wp-submit")
    return any(marker in body for marker in markers)


