def path_variants(url: str) -> list[tuple[str, str]]:
    """Return ``(label, url)`` pairs of functionally equivalent paths."""
    parts = urlsplit(url)
    base = f"{parts.scheme}://{parts.netloc}"
    path = parts.path or "/"
    query = f"?{parts.query}" if parts.query else ""
    variants: list[tuple[str, str]] = []

    def add(label: str, value: str) -> None:
        if value not in [v for _, v in variants]:
            variants.append((label, value))

    add("original-query", f"{url}{'&' if query else '?'}cache=1")
    add("double-slash", f"{base}/{path.lstrip('/')}")
    add("trailing-slash", f"{base}{path}/{query}")
    add("dot-slash", f"{base}/./{path.lstrip('/')}")
    add("encoded-dot", f"{base}/%2e/{path.lstrip('/')}")
    add("case-upper", f"{base}{path.upper()}{query}")
    add("space-suffix", f"{base}{path}%20{query}")
    add("semicolon", f"{base}{path};{query}")
    add("encoded-slash", f"{base}/{path.lstrip('/').replace('/', '%2f', 1)}")
    add("wildcard-path", f"{base}/?/{path.lstrip('/')}")
    add("double-slash-suffix", f"{base}{path}//")
    return variants


